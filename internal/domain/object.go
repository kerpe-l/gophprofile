package domain

import "io"

// StoredObject — объект хранилища, открытый на чтение, вместе с метаданными,
// которые нужны для заголовков ответа.
//
// Тело обязано быть закрыто вызывающим, в том числе если чтение прервалось
// на середине: до Close заняты соединение с хранилищем и горутина чтения
// внутри клиента.
type StoredObject struct {
	// Body — содержимое объекта.
	Body io.ReadCloser
	// ETag — хеш содержимого, каким его отдало хранилище, без обрамляющих
	// кавычек: их добавляет транспорт при записи заголовка.
	ETag string
	// ContentType — тип содержимого, записанный при загрузке.
	ContentType string
	// Size — размер объекта в байтах.
	Size int64
}
